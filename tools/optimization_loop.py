#!/usr/bin/env python3
"""A closed measure-decide loop that picks an execution plan on its own.

This is the piece the project actually claims: not a human choosing a candidate
and checking it, but a loop that explores a space, measures each option against
a frozen threshold, discards what fails, refines around what survives, and
confirms its own winner before reporting it.

Three rounds:

  1. explore  -- a fixed candidate set, measured paired against the baseline
  2. refine   -- neighbours of whatever survived round 1, generated by the loop
  3. confirm  -- the leader re-measured independently; an unreplicated win is
                 reported as unconfirmed rather than as a result

Every candidate passes a correctness gate before its timing counts: an execution
plan may reorder work, never change a single bit of the result.  The statistics
are imported from ``measure_dispatch_plan`` rather than reimplemented, because a
second copy of an estimator is a second chance to get it subtly wrong.

Run with --execute; without it nothing is imported or measured.
"""

from __future__ import annotations

